"""
Клинические константы и пороги.

ЕДИНСТВЕННЫЙ источник правды для всех числовых порогов в проекте.
Каждая константа снабжена ссылкой на источник (PMID/DOI) в комментарии.

ВАЖНО: бот не ставит диагнозов. Пороги используются для формирования
гипотез и флагов, а не для диагностики.
"""
from __future__ import annotations

from typing import Final

# ============================================================================
# Метрики сна (CSD) — Consensus Sleep Diary
# Carney C.E. et al., Sleep 2012;35(2):287–302. PMID 22294820 / DOI 10.5665/sleep.1642
# ============================================================================

# SE < 85% — признак инсомнии (Riemann D. et al., J Sleep Res 2017. PMID 28875581)
SE_INSOMNIA_THRESHOLD: Final[float] = 85.0

# SOL > 30 мин — удлинённая латентность засыпания (PMID 28875581; ICSD-3 PMID 25367475)
SOL_ELEVATED_MIN: Final[int] = 30

# WASO > 30 мин — клинически значимые ночные пробуждения (PMID 28875581)
WASO_ELEVATED_MIN: Final[int] = 30

# TST < 7 ч — недостаточная продолжительность сна
# (Watson N.F. et al., Sleep 2015. PMID 26039963 — 7–9 ч для взрослых)
TST_LOW_HOURS: Final[float] = 7.0

# TIB − TST > 1 ч — «время в постели бодрствуя»
TIB_TST_GAP_HOURS: Final[float] = 1.0

# Для гипотезы «хроническая инсомния» по ICSD-3 требуется ≥ 3 мес симптомов.
# В рамках дневника используем ≥ 3 недель подряд как флаг «обрати внимание»
# (не диагноз). ICSD-3: Sateia M.J., Chest 2014. PMID 25367475
INSOMNIA_MIN_WEEKS: Final[int] = 3

# Недостаточная продолжительность сна: TST < 7 ч на протяжении ≥ 2 недель
TST_LOW_MIN_DAYS: Final[int] = 14

# ============================================================================
# ISI — Insomnia Severity Index (7 пунктов, 0–4, сумма 0–28)
# Bastien C.H. et al., Sleep Med 2001;2(4):297–307. PMID 11438246
# ============================================================================

ISI_BANDS: Final[tuple[tuple[int, int, str], ...]] = (
    (0, 7, "none"),          # нет клинически значимой инсомнии
    (8, 14, "subclinical"),  # субклиническая инсомния
    (15, 21, "moderate"),    # клиническая инсомния (умеренная)
    (22, 28, "severe"),      # тяжёлая клиническая инсомния
)
ISI_CLINICAL_MIN: Final[int] = 15
ISI_MAX_SCORE: Final[int] = 28
ISI_ITEMS_COUNT: Final[int] = 7

# ============================================================================
# PSQI — Pittsburgh Sleep Quality Index (упрощённая версия)
# Buysse D.J. et al., Psychiatry Res 1989;28(2):193–213. PMID 2748771
# ============================================================================

# Глобальный балл > 5 = плохое качество сна
PSQI_POOR_THRESHOLD: Final[int] = 5
# Упрощённая версия: 5 компонентов (латентность, длительность, эффективность,
# нарушения, качество). Опущены: дневная дисфункция, приём препаратов.
# Каждый компонент 0–3, глобальный балл нормируется в шкалу 0–21 (см. methodology.md).
PSQI_MAX_GLOBAL: Final[int] = 21

# ============================================================================
# ESS — Epworth Sleepiness Scale (8 ситуаций, 0–3, сумма 0–24)
# Johns M.W., Sleep 1991;14(6):540–545. PMID 1798888
# ============================================================================

ESS_NORMAL_MAX: Final[int] = 10       # 0–10 норма
ESS_BORDERLINE_MAX: Final[int] = 12   # 11–12 пограничная
ESS_EXCESSIVE_MIN: Final[int] = 13    # > 12 избыточная дневная сонливость
ESS_MAX_SCORE: Final[int] = 24
ESS_ITEMS_COUNT: Final[int] = 8

# ============================================================================
# STOP-BANG — скрининг обструктивного апноэ сна (8 вопросов да/нет)
# Chung F. et al., Chest 2016;149(3):631–638. PMID 26378880
# ============================================================================

STOPBANG_LOW_MAX: Final[int] = 2           # 0–2 низкий риск
STOPBANG_INTERMEDIATE_MAX: Final[int] = 4  # 3–4 промежуточный
STOPBANG_HIGH_MIN: Final[int] = 5          # 5–8 высокий риск
STOPBANG_RISK_MIN: Final[int] = 3          # порог для гипотезы «риск ОАС»
STOPBANG_MAX_SCORE: Final[int] = 8
STOPBANG_ITEMS_COUNT: Final[int] = 8

# ============================================================================
# Гигиена сна / факторы
# ============================================================================

# Кофеин после 16:00 — half-life ~5 ч, влияет на SOL
# Drake C. et al., J Clin Sleep Med 2013. PMID 24235903
CAFFEINE_CUTOFF_HOUR: Final[int] = 16

# Экран за 1 ч до сна — свет блокирует мелатонин
SCREEN_CUTOFF_MIN_BEFORE_BED: Final[int] = 60

# ============================================================================
# Общие ограничения
# ============================================================================

# Минимум ночей для осмысленной статистики (не для гипотез, а для средних)
MIN_ENTRIES_FOR_STATS: Final[int] = 3

# Минимум ночей для гипотезы «хроническая инсомния» (3 недели ≈ 21 день,
# но допускаем пропуски — требуем ≥ 14 записей за 21 день)
INSOMNIA_MIN_ENTRIES: Final[int] = 14